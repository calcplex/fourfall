PALETTE = [(16, 16, 18), (34, 34, 38), (48, 48, 54), (150, 152, 160),
           (176, 178, 188), (245, 245, 245), (235, 235, 240), (112, 224, 208)]
BASE = [(45, 199, 214), (244, 200, 56), (174, 105, 229), (92, 194, 100),
        (235, 89, 91), (73, 127, 226), (244, 147, 53)]
PALETTE += BASE
PALETTE += [tuple(min(255, c + 48) for c in rgb) for rgb in BASE]
PALETTE += [tuple(c * 3 // 5 for c in rgb) for rgb in BASE]
PALETTE += [(120, 120, 128), (207, 77, 72), (255, 255, 255)]
