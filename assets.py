PALETTE += BASE

# Tile numbers: 0 empty cell, 1-7 locked blocks, +16 on the side panels,
# +32 the falling piece, +64 its ghost, 29-31 flash colours.
TILES = [0, *range(1, 8), *range(17, 24), *range(33, 40), *range(65, 72), 29, 30, 31]


def tile(value):
    pixels = [[32 if value & 16 else 0] * 10 for _ in range(10)]
    if not value:
        return [[1 if x == 0 or y == 0 else 0 for x in range(10)] for y in range(10)]
    if value in (29, 30, 31):
        return [[value] * 10 for _ in range(10)]
    if value & 64:
        for y in range(1, 9):
            for x in range(1, 9):
                if x in (1, 8) or y in (1, 8):
                    pixels[y][x] = 29
        return pixels
    color = (value & 15) + 7
    for y in range(1, 10):
        for x in range(1, 10):
            pixels[y][x] = color + (14 if x == 9 or y == 9 else 7 if x == 1 or y == 1 else 0)
    if value & 32:
        for y in (2, 3):
            for x in (2, 3):
                pixels[y][x] = color + 7
    return pixels


def generate(path):
    colors = [(b >> 3) | ((g >> 3) << 5) | ((r >> 3) << 10) for r, g, b in PALETTE]
    lines = [f'.equ palette_bytes, {len(colors) * 2}', 'palette:',
             '.dw ' + ','.join(map(str, colors))]
    for name, glyphs, width, height in [('font_small', GLYPHS, 5, 7),
                                        ('font_medium', MEDIUM_GLYPHS, 7, 10)]:
        lines += [name + ':', f'.db {width},{height},{width + 1}', f'.d24 {name}_data',
                  name + '_data:']
        for code in range(32, 91):
            rows = glyphs.get(chr(code), glyphs[' ']).split()
            assert len(rows) == height and all(len(row) == width for row in rows)
            lines.append('.db ' + ','.join(str(int(row, 2) << (8 - width)) for row in rows))
    lines += ['tile_table:', '.d24 ' + ','.join(
        f'tile_{v if v in TILES else 0}' for v in range(72))]
    for value in TILES:
        lines += [f'tile_{value}:', '.db ' + ','.join(str(p) for row in tile(value) for p in row)]
    path.write_text('\n'.join(lines) + '\n')


def write_icon(path):
    import struct
    import zlib
    pixels = [[PALETTE[0] for _ in range(16)] for _ in range(16)]
    blocks = [(1, 10, 8), (4, 10, 8), (7, 10, 8), (10, 10, 8), (10, 7, 14),
              (10, 4, 14), (7, 7, 14), (4, 3, 10), (7, 3, 10), (10, 3, 10), (7, 6, 10)]
    for x, y, color in blocks:
        for dy in range(3):
            for dx in range(3):
                pixels[y + dy][x + dx] = PALETTE[color + 7 if dy == 0 else color]
    raw = b''.join(b'\0' + bytes(c for rgb in row for c in rgb) for row in pixels)

    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))

    path.write_bytes(b'\x89PNG\r\n\x1a\n' +
                     chunk(b'IHDR', struct.pack('>2I5B', 16, 16, 8, 2, 0, 0, 0)) +
                     chunk(b'IDAT', zlib.compress(raw)) + chunk(b'IEND', b''))
